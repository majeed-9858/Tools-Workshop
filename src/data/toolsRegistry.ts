export const TOOLS_REGISTRY: ToolDefinition[] = RAW_TOOLS_REGISTRY.map((tool) => {
  const customSeo = TOOLS_SEO_MAP[tool.slug] || TOOLS_SEO_MAP[tool.id];
  return {
    ...tool,
    seoTitle: customSeo?.title || `${tool.name} Online – Free Browser Tool | Tools Workshop`,
    seoDescription: customSeo?.description || `${tool.shortDescription} Fast, free, and secure client-side processing with Tools Workshop.`,
  };
});

export const POPULAR_TOOLS = TOOLS_REGISTRY.filter((t) => t.popular);

export function getToolBySlug(slug: string): ToolDefinition | undefined {
  return TOOLS_REGISTRY.find((t) => t.slug === slug || t.id === slug);
}

export function getToolsByCategory(category: string): ToolDefinition[] {
  if (category === 'all') return TOOLS_REGISTRY;
  return TOOLS_REGISTRY.filter((t) => t.category === category);
}

export function searchTools(query: string): ToolDefinition[] {
  if (!query || !query.trim()) return [];
  const q = query.toLowerCase().trim();
  return TOOLS_REGISTRY.filter((tool) => {
    return (
      tool.name.toLowerCase().includes(q) ||
      tool.shortDescription.toLowerCase().includes(q) ||
      (tool.seoTitle && tool.seoTitle.toLowerCase().includes(q)) ||
      tool.category.toLowerCase().includes(q) ||
      tool.keywords.some((k) => k.toLowerCase().includes(q))
    );
  });
}
